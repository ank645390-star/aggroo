async def main():
    client = AsyncIOMotorClient(MONGO_URL)
    db = client[DB_NAME]

    inserted = 0
    base_sort = 1000  # ставимо їх після основних товарів
    for i, (name, cat, short, price, html) in enumerate(EXTRA):
        slug = slugify(name, lowercase=True, max_length=80)
        if await db.products.find_one({"slug": slug}):
            print(f"  · exists: {slug}")
            continue
        first_word = name.split(" ")[0]
        rest = " ".join(name.split(" ")[1:])
        doc = {
            "id": str(uuid.uuid4()),
            "name": name,
            "slug": slug,
            "title_black": first_word,
            "title_grey": rest,
            "full_title": name,
            "short_desc": short,
            "category": cat,
            "photo": PLACEHOLDER,
            "photos": [PLACEHOLDER],
            "packing": "1, 5, 10 л",
            "norm": "",
            "storage_temp": "+5°C – +25°C",
            "storage_period": "2 роки",
            "cultures": "Всі культури",
            "bacteria_genus": "",
            "default_volume": "5 Л",
            "price": price,
            "variants": [],
            "in_stock": True,
            "rating": 4.7,
            "reviews": 0,
            "manual_rating": 4.7,
            "manual_reviews": 0,
            "is_hit": False,
            "is_new": False,
            "is_agronomist_choice": False,
            "sort_order": base_sort + i * 10,
            "is_published": True,
            "status": "published",
            "description_html": "",
            "description_image": PLACEHOLDER,
            "description": {
                "hero_image": PLACEHOLDER,
                "title_line1": first_word,
                "title_line2": "",
                "title_subline": short[:140],
                "chips": [
                    {"icon": "lightning", "title": "Швидка дія",        "body": "", "variant": "green"},
                    {"icon": "eco",       "title": "Екобезпечно",       "body": "", "variant": "dark"},
                    {"icon": "drop",      "title": "Зручне застосування","body": "", "variant": "cream"},
                ],
                "problem":  {"title": "Опис",    "intro_html": html, "outro_html": ""},
                "solution": {"title": "Рішення", "intro_html": "",   "outro_html": ""},
            },
            "dosage":        {"title": "Норма витрати",  "intro": "", "items": [], "note": ""},
            "composition":   {"title": "Склад",           "intro": "", "items": [], "note": ""},
            "compatibility": {"title": "Сумісність",      "intro": "", "items": [], "note": ""},
            "specs":         {"title": "Характеристики",  "intro": "", "items": [], "note": ""},
            "seo_title":     f"{name} | TAMIS АГРО",
            "seo_description": short,
            "created_at":    datetime.now(timezone.utc).isoformat(),
            "updated_at":    datetime.now(timezone.utc).isoformat(),
        }
        await db.products.insert_one(doc)
        inserted += 1
        print(f"  + [{cat:<12}] {name}")

    print(f"\nInserted: {inserted}")
    print("\nFinal counts:")
    for cat in ["biopesticide", "inoculant", "rodenticide", "macro", "adjuvant", "organic"]:
        n = await db.products.count_documents({"category": cat})
        print(f"  {cat:<14} {n}")
    total = await db.products.count_documents({})
    print(f"  TOTAL: {total}")
    client.close()


if __name__ == "__main__":
    asyncio.run(main())
